#!/usr/bin/env bash
# =============================================================================
# deploy-contracts.sh — build, deploy and initialise the escrow and
# marketplace contracts on the running local sandbox.
#
# Usage:  tests/soroban/deploy-contracts.sh [--skip-build]
#
# Writes exportable contract IDs to tests/soroban/.sandbox/contracts.env:
#
#   source tests/soroban/.sandbox/contracts.env
#   echo "$ESCROW_CONTRACT_ID $MARKETPLACE_CONTRACT_ID"
#
# When run under GitHub Actions the same variables are appended to $GITHUB_ENV.
# =============================================================================

set -euo pipefail
# shellcheck source=lib.sh
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

SKIP_BUILD=false
while [[ $# -gt 0 ]]; do
  case "$1" in
    --skip-build) SKIP_BUILD=true; shift ;;
    *) die "Unknown option: $1" ;;
  esac
done

require stellar
rpc_healthy || die "Sandbox RPC is not reachable at ${SANDBOX_RPC_URL} — run sandbox-up.sh first"

if ! ${SKIP_BUILD}; then
  require cargo
  log "Building contracts (release WASM)..."
  (cd "${CONTRACTS_DIR}" && cargo build --release --target wasm32v1-none)
fi

[[ -f "${ESCROW_WASM}" ]] || die "Escrow WASM not found at ${ESCROW_WASM}"
[[ -f "${MARKETPLACE_WASM}" ]] || die "Marketplace WASM not found at ${MARKETPLACE_WASM}"

ADMIN_ADDRESS="$(stellar_cli keys address "${DEPLOYER_IDENTITY}")"

# The escrow contract whitelists settlement tokens at initialisation; use the
# native XLM Stellar Asset Contract, deploying it first on a fresh ledger.
log "Ensuring the native asset contract is deployed..."
stellar_cli contract asset deploy --asset native \
  --source "${DEPLOYER_IDENTITY}" >/dev/null 2>&1 || true
NATIVE_TOKEN_ID="$(stellar_cli contract id asset --asset native)"

deploy() {
  local name="$1" wasm="$2"
  log "Deploying ${name}..." >&2
  stellar_cli contract deploy --wasm "${wasm}" --source "${DEPLOYER_IDENTITY}"
}

ESCROW_CONTRACT_ID="$(deploy escrow "${ESCROW_WASM}")"
log "  escrow:      ${ESCROW_CONTRACT_ID}"
MARKETPLACE_CONTRACT_ID="$(deploy marketplace "${MARKETPLACE_WASM}")"
log "  marketplace: ${MARKETPLACE_CONTRACT_ID}"

log "Initialising escrow..."
stellar_cli contract invoke --id "${ESCROW_CONTRACT_ID}" --source "${DEPLOYER_IDENTITY}" \
  -- initialize --admin "${ADMIN_ADDRESS}" --allowed_tokens "[\"${NATIVE_TOKEN_ID}\"]" >/dev/null

log "Initialising marketplace..."
stellar_cli contract invoke --id "${MARKETPLACE_CONTRACT_ID}" --source "${DEPLOYER_IDENTITY}" \
  -- initialize --admin "${ADMIN_ADDRESS}" >/dev/null

mkdir -p "${SANDBOX_STATE_DIR}"
cat > "${CONTRACTS_ENV_FILE}" <<EOF
# Generated by tests/soroban/deploy-contracts.sh — removed by sandbox-down.sh.
export SOROBAN_NETWORK=${SANDBOX_NETWORK_NAME}
export SOROBAN_RPC_URL=${SANDBOX_RPC_URL}
export SOROBAN_NETWORK_PASSPHRASE="${SANDBOX_PASSPHRASE}"
export SOROBAN_ADMIN_ADDRESS=${ADMIN_ADDRESS}
export NATIVE_TOKEN_CONTRACT_ID=${NATIVE_TOKEN_ID}
export ESCROW_CONTRACT_ID=${ESCROW_CONTRACT_ID}
export ESCROW_CONTRACT_ADDRESS=${ESCROW_CONTRACT_ID}
export MARKETPLACE_CONTRACT_ID=${MARKETPLACE_CONTRACT_ID}
EOF

if [[ -n "${GITHUB_ENV:-}" ]]; then
  sed -n 's/^export //p' "${CONTRACTS_ENV_FILE}" >> "${GITHUB_ENV}"
fi

log "Contract IDs written to ${CONTRACTS_ENV_FILE}:"
sed -n 's/^export /  /p' "${CONTRACTS_ENV_FILE}"
